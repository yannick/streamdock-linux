//! Copyright-free synthetic signals, generated in the test rather than taken from recordings.

pub const RATE: u32 = 44_100;
pub const CHANNELS: u16 = 2;

pub fn pcm(frames: usize, value: i16) -> Vec<u8> {
    std::iter::repeat_n(value.to_le_bytes(), frames * usize::from(CHANNELS))
        .flatten()
        .collect()
}

pub fn wav(frames: usize, value: i16) -> Vec<u8> {
    let pcm = pcm(frames, value);
    let len = u32::try_from(pcm.len()).unwrap();
    let mut body = b"RIFF".to_vec();
    body.extend_from_slice(&(len + 36).to_le_bytes());
    body.extend_from_slice(b"WAVEfmt ");
    body.extend_from_slice(&16_u32.to_le_bytes());
    body.extend_from_slice(&1_u16.to_le_bytes());
    body.extend_from_slice(&CHANNELS.to_le_bytes());
    body.extend_from_slice(&RATE.to_le_bytes());
    body.extend_from_slice(&(RATE * u32::from(CHANNELS) * 2).to_le_bytes());
    body.extend_from_slice(&(CHANNELS * 2).to_le_bytes());
    body.extend_from_slice(&16_u16.to_le_bytes());
    body.extend_from_slice(b"data");
    body.extend_from_slice(&len.to_le_bytes());
    body.extend_from_slice(&pcm);
    body
}

